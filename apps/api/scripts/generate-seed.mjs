/**
 * Generates apps/api/src/seed/catalog.seed.ts from the real storefront
 * catalogue at apps/storefront/src/data/products.ts.
 *
 * The storefront file is the single source of truth for the catalogue
 * (it was itself generated from the preserved legacy storefront). This
 * script parses it with the TypeScript compiler API and re-emits the
 * `products` and `categories` arrays as a typed seed module for the
 * API's in-memory repositories. Run from the monorepo root:
 *
 *   node apps/api/scripts/generate-seed.mjs
 *
 * Re-run it whenever the storefront catalogue changes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = resolve(
  here,
  '../../storefront/src/data/products.ts',
);
const outPath = resolve(here, '../src/seed/catalog.seed.ts');

const sourceText = readFileSync(sourcePath, 'utf8');
const sf = ts.createSourceFile(
  sourcePath,
  sourceText,
  ts.ScriptTarget.Latest,
  true,
);

/** Converts a TS literal expression node into a plain JS value. */
function literalValue(node) {
  if (ts.isStringLiteral(node)) return node.text;
  if (ts.isNumericLiteral(node)) return Number(node.text);
  if (node.kind === ts.SyntaxKind.TrueKeyword) return true;
  if (node.kind === ts.SyntaxKind.FalseKeyword) return false;
  if (node.kind === ts.SyntaxKind.NullKeyword) return null;
  if (ts.isPrefixUnaryExpression(node)) {
    const v = literalValue(node.operand);
    if (node.operator === ts.SyntaxKind.MinusToken) return -v;
    return v;
  }
  if (ts.isArrayLiteralExpression(node)) {
    return node.elements.map(literalValue);
  }
  if (ts.isObjectLiteralExpression(node)) {
    const out = {};
    for (const prop of node.properties) {
      if (!ts.isPropertyAssignment(prop)) {
        throw new Error('Unsupported property in catalogue literal');
      }
      const key = ts.isIdentifier(prop.name)
        ? prop.name.text
        : prop.name.text;
      out[key] = literalValue(prop.initializer);
    }
    return out;
  }
  throw new Error(
    `Unsupported literal kind in catalogue: ${ts.SyntaxKind[node.kind]}`,
  );
}

const wanted = new Map();
function visit(node) {
  if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name)) {
    const name = node.name.text;
    if ((name === 'products' || name === 'categories') && node.initializer) {
      wanted.set(name, literalValue(node.initializer));
    }
  }
  ts.forEachChild(node, visit);
}
visit(sf);

const products = wanted.get('products');
const categories = wanted.get('categories');
if (!Array.isArray(products) || products.length === 0) {
  throw new Error('products array not found in storefront data');
}
if (!Array.isArray(categories) || categories.length === 0) {
  throw new Error('categories array not found in storefront data');
}

const header = `/**
 * GENERATED FILE. Do not edit by hand.
 *
 * Generated by apps/api/scripts/generate-seed.mjs from the real
 * storefront catalogue at apps/storefront/src/data/products.ts
 * (${products.length} products, ${categories.length} categories, real prices and
 * stock). Re-run the generator when the storefront catalogue changes.
 */

export interface SeedProduct {
  id: string;
  name: string;
  cat: string;
  /** Whole taka, exactly as the storefront data carries it. */
  price: number;
  /** Compare-at price in whole taka, 0 when there is none. */
  was: number;
  badge: string;
  stock: number;
  sizes: string[];
  img: string;
  gallery: string[];
  /** Colour variants: [name, swatch hex, photo]. */
  vars: [string, string, string][];
  /** Swatches: [name, hex]. */
  sw: [string, string][];
  desc: string;
  spec: [string, string][];
}

export interface SeedCategory {
  name: string;
  img: string;
  alt: string;
}

`;

const body =
  header +
  `export const SEED_PRODUCTS: SeedProduct[] = ${JSON.stringify(products, null, 2)};\n\n` +
  `export const SEED_CATEGORIES: SeedCategory[] = ${JSON.stringify(categories, null, 2)};\n`;

writeFileSync(outPath, body, 'utf8');
console.log(
  `Wrote ${outPath}: ${products.length} products, ${categories.length} categories`,
);
